export function translateProgress(message: string, language: Language): string {
  if (language === 'en') return message;
  if (persian[message]) return persian[message];
  const patterns: [RegExp, (...parts: string[]) => string][] = [
    [/^Fetching page (\d+)\.\.\.$/, page => `در حال دریافت صفحه ${page}...`],
    [/^Analyzing post (\d+)\.\.\.$/, post => `در حال تحلیل پست ${post}...`],
    [/^Downloading post (\d+)\.\.\.$/, post => `در حال دانلود پست ${post}...`],
    [/^Checked quality (\d+)\/(\d+)$/, (done, total) => `کیفیت بررسی شد: ${done}/${total}`],
    [/^Checked (\d+)\/(\d+) posts$/, (done, total) => `پست‌های بررسی‌شده: ${done}/${total}`],
    [/^Imported (\d+)\/(\d+) records$/, (done, total) => `رکوردهای واردشده: ${done}/${total}`],
    [/^Imported (\d+) saved\/liked records$/, count => `${count} رکورد ذخیره/لایک وارد شد`],
    [/^Copying (\d+)\/(\d+) files$/, (done, total) => `فایل‌های کپی‌شده: ${done}/${total}`],
    [/^Scanning archive: (\d+) files found$/, count => `در حال پیمایش آرشیو؛ ${count} فایل دیده شد`],
    [/^Archive scan complete: (\d+) files$/, count => `پیمایش کامل شد؛ ${count} فایل برای کپی`],
    [/^Organizing category (\d+)\/(\d+)\.\.\.$/, (done, total) => `دسته‌های سازمان‌دهی‌شده: ${done}/${total}`],
  ];
  for (const [pattern, format] of patterns) {
    const match = message.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return message;
}

type I18n = { language: Language; setLanguage: (next: Language) => void; t: (text: string) => string };
const Context = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => localStorage.getItem('appLanguage') === 'en' ? 'en' : 'fa');
  useEffect(() => {
    localStorage.setItem('appLanguage', language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'fa' ? 'rtl' : 'ltr';
  }, [language]);
  const t = (text: string) => {
    if (!text) return text;
    const translated = language === 'en' ? englishLookup[text] || text : persianLookup[text] || text;
    return text.endsWith(':') && !translated.endsWith(' ') ? translated + ' ' : translated;
  };
  return <Context.Provider value={{ language, setLanguage, t }}>{children}</Context.Provider>;
}

export function useI18n() {
  const value = useContext(Context);
  if (!value) throw new Error('I18nProvider is missing');
  return value;
}
